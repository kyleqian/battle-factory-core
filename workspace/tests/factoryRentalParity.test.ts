// Differential spec for core-rs/adapter/factoryEngine.ts: proves the TS
// engine (src/engine/factoryRentalGeneration.ts) and the factory-wasm
// engine (fw_generate_initial_rentals) agree on Battle Factory initial-rental
// generation for identical inputs — full result including the complete
// drawLedger — not just that either one individually looks right.
//
// Availability rules mirror tests/rngEngineParity.test.ts (see that file's
// header for the rationale): POKEBENCH_ENGINE=wasm with the artifact
// missing is a hard failure; the artifact merely being absent (no opt-in)
// skips only the wasm-dependent suites via describe.skipIf, and the TS
// engine's own throws are exercised directly (no wasm needed) wherever
// this file calls generateInitialFactoryRentals outside those suites.
//
// Invocations (from the workspace root):
//   ./core-rs/build-wasm.sh
//   NODE_OPTIONS=--max-old-space-size=8192 npx vitest run tests/factoryRentalParity.test.ts --no-watch --pool=forks
//   POKEBENCH_ENGINE=wasm NODE_OPTIONS=--max-old-space-size=8192 npx vitest run tests/factoryRentalParity.test.ts --no-watch --pool=forks

import { existsSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  defaultEngineId,
  resolveWasmArtifactPath,
} from "../core-rs/adapter/rngEngine.ts";
import { wasmFactoryEngine, type FactoryEngine } from "../core-rs/adapter/factoryEngine.ts";
import {
  generateInitialFactoryRentals,
  type FactoryInitialRentalGenerationInput,
  type FactoryInitialRentalGenerationResult,
} from "../src/engine/factoryRentalGeneration.ts";
import { advanceRngValue } from "../src/engine/rng.ts";

const requestedEngine = defaultEngineId();
const wasmArtifactPath = resolveWasmArtifactPath();
const wasmAvailable = existsSync(wasmArtifactPath);

if (requestedEngine === "wasm" && !wasmAvailable) {
  throw new Error(
    `POKEBENCH_ENGINE=wasm requires the factory-wasm artifact at ${wasmArtifactPath}, ` +
      `which does not exist. Build it with: core-rs/build-wasm.sh`,
  );
}

let wasmEnginePromise: Promise<FactoryEngine> | undefined;
function getWasmEngine(): Promise<FactoryEngine> {
  wasmEnginePromise ??= wasmFactoryEngine();
  return wasmEnginePromise;
}

const PLAYER_TRAINER_ID = 0x1234_5678;

// --- deterministic config matrix --------------------------------------
//
// 16 seeds: 3 fixed boundary/anchor values plus 13 more generated by
// iterating the TS engine's advanceRngValue from the anchor seed (no
// Date/Math.random — this file must be fully deterministic) x 3
// factoryWinStreak values x 3 rentsCount values x 2 constructionRngValue
// values = 288 configs total, run in full below (no trimming was needed —
// each config's generate+compare is sub-millisecond; see the final report
// for observed wall-clock).
const SEEDS: number[] = (() => {
  const seeds = [0x0000_0000, 0xd2dd_eec8, 0xffff_ffff];
  let cursor = 0xd2dd_eec8;
  while (seeds.length < 16) {
    cursor = advanceRngValue(cursor) >>> 0;
    seeds.push(cursor);
  }
  return seeds;
})();

const FACTORY_WIN_STREAKS = [0, 21, 49] as const;
const RENTS_COUNTS = [0, 20, 100] as const;
const CONSTRUCTION_RNG_VALUES = [undefined, 0x7399_e3ae] as const;

interface MatrixConfig {
  readonly seed: number;
  readonly factoryWinStreak: number;
  readonly rentsCount: number;
  readonly constructionRngValue: number | undefined;
}

const MATRIX: MatrixConfig[] = (() => {
  const matrix: MatrixConfig[] = [];
  for (const seed of SEEDS) {
    for (const factoryWinStreak of FACTORY_WIN_STREAKS) {
      for (const rentsCount of RENTS_COUNTS) {
        for (const constructionRngValue of CONSTRUCTION_RNG_VALUES) {
          matrix.push({ seed, factoryWinStreak, rentsCount, constructionRngValue });
        }
      }
    }
  }
  return matrix;
})();

function describeConfig(config: MatrixConfig): string {
  const seedHex = `0x${(config.seed >>> 0).toString(16).padStart(8, "0")}`;
  const constructionText = config.constructionRngValue === undefined
    ? "undefined"
    : `0x${config.constructionRngValue.toString(16)}`;
  return `seed=${seedHex} winStreak=${config.factoryWinStreak} rentsCount=${config.rentsCount} `
    + `constructionRngValue=${constructionText}`;
}

function toInput(config: MatrixConfig): FactoryInitialRentalGenerationInput {
  return {
    rngValue: config.seed,
    factoryWinStreak: config.factoryWinStreak,
    rentsCount: config.rentsCount,
    playerTrainerId: PLAYER_TRAINER_ID,
    constructionRngValue: config.constructionRngValue,
  };
}

function tryGenerate(
  generate: (input: FactoryInitialRentalGenerationInput) => FactoryInitialRentalGenerationResult,
  input: FactoryInitialRentalGenerationInput,
): { result: FactoryInitialRentalGenerationResult; error?: undefined } | { result?: undefined; error: string } {
  try {
    return { result: generate(input) };
  } catch (err) {
    return { error: (err as Error).message };
  }
}

// --- Part A: full-result differential matrix -------------------------------
//
// Some configs are genuine TS-engine error states (challengeNum 7 with a
// better-range slot has no fixed-IV table row — confirmed against the live
// TS engine; see core-rs/crates/factory-core/src/rental_generation.rs's
// GenerationError::FixedIvUndefined doc comment), reachable here at
// factoryWinStreak 49 with rentsCount 20 or 100 regardless of seed. Those
// configs assert error-message parity instead of result equality.

describe.skipIf(!wasmAvailable)("Battle Factory initial-rental generation — ts vs wasm full matrix", () => {
  MATRIX.forEach((config, index) => {
    it(`[${index}/${MATRIX.length}] ${describeConfig(config)}`, async () => {
      const engine = await getWasmEngine();
      const input = toInput(config);
      const label = describeConfig(config);

      const ts = tryGenerate(generateInitialFactoryRentals, input);
      const wasm = tryGenerate((i) => engine.generateInitialFactoryRentals(i), input);

      if (ts.error !== undefined || wasm.error !== undefined) {
        expect(wasm.error, `${label}: error-message parity (ts threw ${JSON.stringify(ts.error)})`).toBe(ts.error);
        return;
      }
      expect(wasm.result, `${label}: full-result parity (including drawLedger)`).toEqual(ts.result);
    });
  });
});

// --- Part B: dedicated error parity — factoryWinStreak 56 (challengeNum 8) -

describe.skipIf(!wasmAvailable)("Error parity — challenge 8 rejects on both engines", () => {
  it("factoryWinStreak 56 (challengeNum 8): ts throws and wasm's message mentions the same 0..7 constraint", async () => {
    const engine = await getWasmEngine();
    const input: FactoryInitialRentalGenerationInput = {
      rngValue: 0,
      factoryWinStreak: 56,
      rentsCount: 0,
      playerTrainerId: PLAYER_TRAINER_ID,
    };

    expect(() => generateInitialFactoryRentals(input)).toThrow(
      "Level-50 initial rental generation supports source challenges 0..7, got 8",
    );
    const wasm = tryGenerate((i) => engine.generateInitialFactoryRentals(i), input);
    expect(wasm.error).toBeDefined();
    expect(wasm.error).toMatch(/0\.\.7/);
    expect(wasm.error).toBe(
      "Level-50 initial rental generation supports source challenges 0..7, got 8",
    );
  });
});

// --- Part C: seed-0 pin anchoring both engines to the recorded fixture -----
//
// tests/factoryRentalGeneration.test.ts "pins the challenge-0 six full
// records and every one of 198 Random() calls for seed 0" is the recorded
// fixture; this reproduces its exact compact-record values against the
// WASM engine directly (not merely against the TS engine), so both engines
// anchor to the same recorded evidence rather than only to each other.

function compactRecords(result: FactoryInitialRentalGenerationResult) {
  return result.rentals.map((rental) => ({
    setId: rental.setId,
    personality: rental.personality,
    fixedIv: rental.fixedIv,
    abilitySlot: rental.abilitySlot,
    otId: rental.otId,
    speciesName: rental.speciesName,
    itemId: rental.itemId,
    nature: rental.nature,
    selectionDrawPosition: rental.selectionDrawPosition,
    personalityDrawPositions: rental.personalityDrawPositions,
  }));
}

