#!/usr/bin/env python3
"""aud241b: generate src/data/faintCryFrames.ts -- frames from PlayCry_ByMode(CRY_MODE_FAINT) to the BGM-duck restore
(Task_DuckBGMForPokemonCry sees !IsCryPlaying), per Factory species.

CRY_MODE_FAINT (sound.c PlayCryInternal) = pitch 14440, release 200, length 140. The restore delay is a linear fit of the
cry sample's native duration t = size * 16777216 / (rate * 280896) frames (the offs152 NORMAL-mode input) to 15 ROM
step-mode windows (tools/audio/fixtures/faint-cry-length-*.json): delay = ceil(1.205 * t + 0.91), exact on all 15 measured
species (t 10.8 .. 69.6). Unmeasured species are a fit, not a measurement (docs/aud241b-battle-sounds.md).
  python3 tools/audio/genFaintCryTable.py [out.ts]     (default: src/data/faintCryFrames.ts)"""
import json, math, re, struct, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
ref = root / "reference/pokeemerald"
ids = sorted(json.load(open(root / "tools/integration/fixtures/forced-switch/factory-species-ids.json")))
names = {r["id"]: r["name"] for r in json.load(open(root / "src/data/gen/species-stats.json"))["species"]}
table = [l.split()[1] for l in open(ref / "sound/cry_tables.inc") if l.strip().startswith("cry ")]
incbin, cur = {}, None
for line in open(ref / "sound/direct_sound_data.inc"):
    m = re.match(r"(Cry_\w+)::", line.strip())
    if m:
        cur = m.group(1)
        continue
    b = re.search(r'\.incbin "(sound/direct_sound_samples/cries/[^"]+\.bin)"', line)
    if b and cur:
        incbin[cur.lower()] = (cur, b.group(1))
        cur = None
GBA_CPU_HZ, CYCLES_PER_FRAME = 16777216, 280896
K, C = 1.205, 0.91
rows = {}
for sp in ids:
    key = "cry_" + names[sp].replace("SPECIES_", "").lower().replace("_", "")
    symbol, path = incbin[key]
    assert symbol in table, symbol
    _type, _status, freq, _loop, size = struct.unpack("<HHIII", open(ref / path, "rb").read(16))
    t = size * GBA_CPU_HZ / ((freq // 1024) * CYCLES_PER_FRAME)
    rows[sp] = math.ceil(K * t + C)
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "src/data/faintCryFrames.ts"
L = [
    "// GENERATED by tools/audio/genFaintCryTable.py from reference/pokeemerald/sound/ (cry_tables.inc, direct_sound_data.inc, the",
    "// compiled cries/*.bin WaveData headers) -- do not edit.",
    "// aud241b (docs/aud241b-battle-sounds.md): frames from a CRY_MODE_FAINT cry start to the BGM-duck restore.",
    "",
    "/** species -> frames from the PlayCry_ByMode(CRY_MODE_FAINT) call to the duck restore (ceil(1.205 * native cry frames + 0.91), exact on 15 ROM species). */",
    "export const FAINT_CRY_RESTORE_FRAMES: Readonly<Record<number, number>> = Object.freeze({",
]
items = [f"{sp}: {rows[sp]}" for sp in ids]
for i in range(0, len(items), 10):
    L.append("  " + ", ".join(items[i:i + 10]) + ",")
L.append("});")
out.write_text("\n".join(L) + "\n")
print(f"{out}: {len(rows)} species, restore delay {min(rows.values())}..{max(rows.values())}")
