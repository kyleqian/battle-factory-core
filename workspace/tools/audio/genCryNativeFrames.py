#!/usr/bin/env python3
"""cry1: generate src/data/cryNativeFrames.ts -- the native NORMAL-mode length t = size * 16777216 / ((freq // 1024) * 280896) of each Factory species' cry
sample (the aud241b / send-in-tail-off basis), unrounded to 5 decimals. src/engine/cryTaskLengths.ts turns it into the per-mode IsCryPlaying lengths.
  python3 tools/audio/genCryNativeFrames.py [out.ts]     (default: src/data/cryNativeFrames.ts)"""
import json, re, struct, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
ref = root / "reference/pokeemerald"
ids = sorted(json.load(open(root / "tools/integration/fixtures/forced-switch/factory-species-ids.json")))
names = {r["id"]: r["name"] for r in json.load(open(root / "src/data/gen/species-stats.json"))["species"]}
incbin, cur = {}, None
for line in open(ref / "sound/direct_sound_data.inc"):
    m = re.match(r"(Cry_\w+)::", line.strip())
    if m:
        cur = m.group(1)
        continue
    b = re.search(r'\.incbin "(sound/direct_sound_samples/cries/[^"]+\.bin)"', line)
    if b and cur:
        incbin[cur.lower()] = b.group(1)
        cur = None
rows = {}
for sp in ids:
    path = incbin["cry_" + names[sp].replace("SPECIES_", "").lower().replace("_", "")]
    _type, _status, freq, _loop, size = struct.unpack("<HHIII", open(ref / path, "rb").read(16))
    rows[sp] = round(size * 16777216 / ((freq // 1024) * 280896), 5)
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "src/data/cryNativeFrames.ts"
L = [
    "// GENERATED by tools/audio/genCryNativeFrames.py from reference/pokeemerald/sound/ (direct_sound_data.inc, the compiled cries/*.bin WaveData headers) -- do not edit.",
    "",
    "/** species -> native cry length in frames, size * 16777216 / ((freq // 1024) * 280896), 5 decimals. */",
    "export const CRY_NATIVE_FRAMES: Readonly<Record<number, number>> = Object.freeze({",
]
items = [f"{sp}: {rows[sp]}" for sp in ids]
for i in range(0, len(items), 8):
    L.append("  " + ", ".join(items[i:i + 8]) + ",")
L.append("});")
out.write_text("\n".join(L) + "\n")
print(f"{out}: {len(rows)} species")
