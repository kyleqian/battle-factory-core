// dl4: writes src/engine/animAssetsFull.ts, the full table of every `src/animation/assets/*.json` (static imports, so node tools and
// vitest read them synchronously). tests/dl4AnimAssets.test.ts fails when the file is out of date; regenerate with
//   node --experimental-strip-types tools/build/generateAnimAssetsFull.ts
import { readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

export function animAssetNames(root = "."): string[] {
  return readdirSync(resolve(root, "src/animation/assets")).filter((file) => file.endsWith(".json")).map((file) => file.slice(0, -5)).sort();
}

export function animAssetsFullSource(names: readonly string[]): string {
  const ident = (name: string, index: number): string => `a${index}`;
  return [
    "// GENERATED by tools/build/generateAnimAssetsFull.ts: do not edit. The full table of the animation asset files (dl4); see animAssets.ts.",
    "// Imported by animAssetsInstall.ts only (node tools, vitest, the dev shell's bench ABI); the browser library loads per-asset files instead.",
    ...names.map((name, index) => `import ${ident(name, index)} from "../animation/assets/${name}.json" with { type: "json" };`),
    "",
    "export const FULL_ANIM_ASSETS: Readonly<Record<string, object>> = {",
    ...names.map((name, index) => `  ${JSON.stringify(name)}: ${ident(name, index)},`),
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(resolve("src/engine/animAssetsFull.ts"), animAssetsFullSource(animAssetNames()));
}
