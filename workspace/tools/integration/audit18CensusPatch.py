#!/usr/bin/env python3
"""Live audit 18 target 3: writes audit18Census713.ts = the given tree's liveShareCensus.ts + a per-command `hosts` record (the
orchestrator's allocator history / order host state at the command's first frame, the view's sprite-allocator input, the battler sprites
shown). tools/integration/audit18Census713.ts is this applied to master 3dd7835fd's census; audit18Run.sh applies it to 82690e775's.
usage: audit18CensusPatch.py <liveShareCensus.ts> <out.ts>"""
import sys
from pathlib import Path

s = Path(sys.argv[1]).read_text()
old = '''        status: "fallback", frames: 0, liveFrames: 0, swapFrames: 0, duration,'''
new = '''        status: "fallback", frames: 0, liveFrames: 0, swapFrames: 0, duration,
        // audit18Census713: the orchestrator's hosts at the command's first frame (allocator history, order host) + its sprite inputs
        hosts: ((s: any, v: any) => ({ alloc: s.liveMoveSpriteAllocatorHost?.host?.historyKnown ?? null,
          order: s.liveMoveSpriteAllocatorHost?.orderHost ? (s.liveMoveSpriteAllocatorHost.orderHost.tracker.invalidReason
            ?? (s.liveMoveSpriteAllocatorHost.orderHost.tracker.cursor.order.known ? "known" : "unknown")) : null,
          allocInput: v.effect?.spriteAllocatorInput === undefined ? null : v.effect.spriteAllocatorInput.historyKnown ?? true,
          spriteShown: v.visibility ? [v.visibility.player.sprite, v.visibility.opponent.sprite] : null }))(state, view),'''
assert old in s
s = s.replace(old, new)
s = "// audit18Census713.ts (generated by audit18CensusPatch.py) = liveShareCensus.ts + per-command host state (`hosts`); live audit 18 target 3.\n" + s
Path(sys.argv[2]).write_text(s)
