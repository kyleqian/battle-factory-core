#!/usr/bin/env python3
"""snd145 (S10A, ISSUES #146 remainder; docs/send-in-tail-model.md §1.1, docs/snd145-send-in-tail-live.md): generate
src/data/sendInTail.ts — the per-species send-in tail inputs for the Factory species from the committed fixtures:

  S[sp]        sum of ANIMCMD_FRAME durations of sAnim_<Name>_1 (front_pic_anims.h; fixtures/send-in-tail/front-sprite-frames.json)
  animId/delay sMonFrontAnimIdsTable / sMonAnimationDelayTable (pokemon.c:1405,1795; fixtures/send-in-tail/front-anim-tables.json)
  A[animId]    sMonAnimFunctions callback length, fitted on the 339-species ROM sweep (fixtures/send-in-tail/anim-duration.json, 46 ids)
  message      slide + 26 except the 7 swept cry-bound species (measured offsets; fixtures/forced-switch/species-sweep-opponent-target.txt)

Species = fixtures/forced-switch/factory-species-ids.json (every Factory rental species, 376; 339 swept, 37 failed lab validation).
  python3 tools/integration/snd145GenTable.py [out.ts]     (default: src/data/sendInTail.ts)"""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
fx = root / "tools/integration/fixtures"
T = json.load(open(fx / "send-in-tail/front-anim-tables.json"))
S = json.load(open(fx / "send-in-tail/front-sprite-frames.json"))
A = json.load(open(fx / "send-in-tail/anim-duration.json"))
ids = sorted(json.load(open(fx / "forced-switch/factory-species-ids.json")))
exc = {}
for l in open(fx / "forced-switch/species-sweep-opponent-target.txt"):
    m, t = re.search(r"hbslide (\d+)", l), re.search(r"txtStart (\d+)", l)
    if m and t and int(t.group(1)) - int(m.group(1)) != 26:
        exc[int(l.split()[0])] = int(t.group(1)) - int(m.group(1))
anim_names = sorted({T[str(sp)][0] for sp in ids})
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "src/data/sendInTail.ts"
L = []
L.append("// GENERATED by tools/integration/snd145GenTable.py from tools/integration/fixtures/{send-in-tail,forced-switch}/ -- do not edit.")
L.append("// snd145 (S10A, ISSUES #146 remainder; docs/send-in-tail-model.md, docs/snd145-send-in-tail-live.md): the species-keyed send-in tail.")
L.append("// Opponent: the healthbox slide is released by SwitchIn_ShowHealthbox (battle_controller_opponent.c:482-498) once the battler sprite")
L.append("// callback is SpriteCallbackDummy, i.e. after the front animation: max(frame anim S, delay - 1 + function anim A) (pokemon.c:6784-6856,")
L.append("// pokemon_animation.c:5540); the message follows 26 frames later except for the swept cry-bound species (SwitchIn_HandleSoundAndEnd).")
L.append("// Player: slide send-in +65 constant (338 / 339 swept; Castform +66); the player message is cry-bound and not modelled here.")
L.append("")
L.append("/** Opponent slide = SEND_IN_TAIL_BASE + castform + max(S, A + delay - 1), frames after the send-in start (ROM RAM; sweep k - 10). */")
L.append("export const SEND_IN_TAIL_BASE = 36;")
L.append("export const SEND_IN_TAIL_PLAYER_SLIDE = 65;")
L.append("export const SEND_IN_TAIL_MESSAGE_AFTER_SLIDE = 26;")
L.append("export const SEND_IN_TAIL_CASTFORM = 385;")
L.append("/** sMonAnimFunctions callback length per front animation id (fitted, 46 ids; absent = never dominates a swept species: 0). */")
L.append("export const SEND_IN_TAIL_FRONT_ANIM_DURATION: Readonly<Record<string, number>> = Object.freeze({")
for k in sorted(A):
    L.append(f"  {k}: {A[k]},")
L.append("});")
L.append("/** Front animation ids used by the Factory species (index into the per-species rows). */")
L.append("export const SEND_IN_TAIL_ANIM_IDS: readonly string[] = Object.freeze([")
for k in anim_names:
    L.append(f'  "{k}",')
L.append("]);")
L.append("/** species -> [S (front sprite frame-anim length), anim id index, sMonAnimationDelayTable delay]. */")
L.append("export const SEND_IN_TAIL_SPECIES: Readonly<Record<number, readonly [number, number, number]>> = Object.freeze({")
row = []
for sp in ids:
    a, d = T[str(sp)]
    row.append(f"{sp}: [{S.get(str(sp), 0)}, {anim_names.index(a)}, {d}]")
for i in range(0, len(row), 6):
    L.append("  " + ", ".join(row[i:i + 6]) + ",")
L.append("});")
L.append("/** Swept cry-bound opponent species: message start - slide start (measured; every other species: 26). */")
L.append("export const SEND_IN_TAIL_MESSAGE_EXCEPTIONS: Readonly<Record<number, number>> = Object.freeze({")
L.append("  " + ", ".join(f"{k}: {v}" for k, v in sorted(exc.items())) + ",")
L.append("});")
L.append("")
L.append("export type SendInTail = Readonly<{ slideStart: number; messageStart: number | null }>;")
L.append("")
L.append("/**")
L.append(" * The send-in tail of one send-in, in frames after the send-in start (ROM RAM, `switchinanim`'s controller start = sweep k10):")
L.append(" * `slideStart` = StartHealthboxSlideIn, `messageStart` = the next printstring's first glyph (null = not modelled: the player side's")
L.append(" * cry-bound message). Species outside the table (none in the Factory) fall back to the frame-animation-free base.")
L.append(" */")
L.append("export function sendInTail(species: number, side: \"player\" | \"opponent\"): SendInTail {")
L.append("  const castform = species === SEND_IN_TAIL_CASTFORM ? 1 : 0;")
L.append("  if (side === \"player\") return Object.freeze({ slideStart: SEND_IN_TAIL_PLAYER_SLIDE + castform, messageStart: null });")
L.append("  const row = SEND_IN_TAIL_SPECIES[species];")
L.append("  const frames = row?.[0] ?? 0;")
L.append("  const fn = row === undefined ? 0 : (SEND_IN_TAIL_FRONT_ANIM_DURATION[SEND_IN_TAIL_ANIM_IDS[row[1]]!] ?? 0) + (row[2] > 0 ? row[2] - 1 : 0);")
L.append("  const slideStart = SEND_IN_TAIL_BASE + castform + Math.max(frames, fn);")
L.append("  return Object.freeze({")
L.append("    slideStart,")
L.append("    messageStart: slideStart + (SEND_IN_TAIL_MESSAGE_EXCEPTIONS[species] ?? SEND_IN_TAIL_MESSAGE_AFTER_SLIDE),")
L.append("  });")
L.append("}")
out.write_text("\n".join(L) + "\n")
print(f"{out}: {len(ids)} species, {len(A)} anim durations, {len(exc)} message exceptions")
