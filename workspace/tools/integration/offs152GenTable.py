#!/usr/bin/env python3
"""offs152 (S10A, ISSUES #146 remainder; docs/offs152-scene-off-send-in-tail.md): generate src/data/sendInTailOff.ts -- the Scene OFF
opponent send-in tail input per Factory species: the send-in cry's length in frames, from SOURCE data only.

The cry (Task_PlayCryWhenReleasedFromBall -> PlayCry_ByMode(species, pan, CRY_MODE_NORMAL), pokeball.c:686-693) plays the species'
compiled DirectSound sample (sound/cry_tables.inc `cry Cry_<Name>` -> sound/direct_sound_data.inc `.incbin ".../cries/<name>.bin"`)
at its native rate: CRY_MODE_NORMAL keeps pitch 15360 (= key 60 = the voice's base key, sound.c:383-392) and note length 140 (longer
than any cry), so the channel frees when the sample ends. Frames = ceil(samples * GBA_CPU_HZ / (rate * CYCLES_PER_FRAME)) with samples
and rate (freq / 1024) from the .bin's WaveData header (u16 type, u16 status, u32 freq, u32 loopStart, u32 size).
SwitchIn_HandleSoundAndEnd (battle_controller_opponent.c:469-480) waits for !IsCryPlayingOrClearCrySongs.
Species = tools/integration/fixtures/forced-switch/factory-species-ids.json (376).
  python3 tools/integration/offs152GenTable.py [out.ts]     (default: src/data/sendInTailOff.ts)"""
import json, re, struct, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
ref = root / "reference/pokeemerald"
ids = sorted(json.load(open(root / "tools/integration/fixtures/forced-switch/factory-species-ids.json")))
names = {r["id"]: r["name"] for r in json.load(open(root / "src/data/gen/species-stats.json"))["species"]}
table = [l.split()[1] for l in open(ref / "sound/cry_tables.inc") if l.strip().startswith("cry ")]
incbin, cur = {}, None
for line in open(ref / "sound/direct_sound_data.inc"):
    m = re.match(r"(Cry_\w+)::", line.strip())
    if m:
        cur = m.group(1)
        continue
    b = re.search(r'\.incbin "(sound/direct_sound_samples/cries/[^"]+\.bin)"', line)
    if b and cur:
        incbin[cur.lower()] = (cur, b.group(1))
        cur = None
GBA_CPU_HZ, CYCLES_PER_FRAME = 16777216, 280896
rows = {}
for sp in ids:
    key = "cry_" + names[sp].replace("SPECIES_", "").lower().replace("_", "")
    symbol, path = incbin[key]
    assert symbol in table, symbol
    _type, _status, freq, _loop, size = struct.unpack("<HHIII", open(ref / path, "rb").read(16))
    rate = freq // 1024
    rows[sp] = -(-size * GBA_CPU_HZ // (rate * CYCLES_PER_FRAME))
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "src/data/sendInTailOff.ts"
L = [
    "// GENERATED by tools/integration/offs152GenTable.py from reference/pokeemerald/sound/ (cry_tables.inc, direct_sound_data.inc, the",
    "// compiled cries/*.bin WaveData headers) -- do not edit.",
    "// offs152 (S10A, ISSUES #146 remainder; docs/offs152-scene-off-send-in-tail.md): the Scene OFF opponent send-in tail's cry input.",
    "",
    "/** species -> the CRY_MODE_NORMAL send-in cry's length in frames (ceil(samples * 16777216 / (rate * 280896))). */",
    "export const SEND_IN_TAIL_OFF_CRY_FRAMES: Readonly<Record<number, number>> = Object.freeze({",
]
items = [f"{sp}: {rows[sp]}" for sp in ids]
for i in range(0, len(items), 10):
    L.append("  " + ", ".join(items[i:i + 10]) + ",")
L.append("});")
out.write_text("\n".join(L) + "\n")
print(f"{out}: {len(rows)} species, cry frames {min(rows.values())}..{max(rows.values())}")
